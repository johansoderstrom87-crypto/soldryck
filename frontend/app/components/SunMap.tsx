/** Snap (lat,lng) to nearest point on pre-smoothed tracks. Returns position, color,
 *  local tangent direction, plus which track and segment index for neighbor computation. */
function snapToTrack(
  lat: number,
  lng: number,
  tracks: { color: "red" | "green" | "blue"; coords: [number, number][] }[],
): SnapResult {
  let bestDist = Infinity;
  let bestPos: [number, number] = [lat, lng];
  let bestColor: "red" | "green" | "blue" = "red";
  let bestDir: [number, number] = [1, 0];
  let bestTrackIdx = 0, bestSegIdx = 0;
  const cosLat = Math.cos((lat * Math.PI) / 180);

  for (let ti = 0; ti < tracks.length; ti++) {
    const c = tracks[ti].coords as [number, number][];
    for (let i = 0; i < c.length - 1; i++) {
      const pt = nearestOnSegment(lat, lng, c[i], c[i + 1]);
      const dlat = pt[0] - lat, dlng = (pt[1] - lng) * cosLat;
      const d2 = dlat * dlat + dlng * dlng;
      if (d2 < bestDist) {
        bestDist = d2; bestPos = pt; bestColor = tracks[ti].color;
        bestTrackIdx = ti; bestSegIdx = i;
        const sdLat = c[i + 1][0] - c[i][0], sdLng = c[i + 1][1] - c[i][1];
        const norm = Math.hypot(sdLat, sdLng * cosLat) || 1;
        bestDir = [sdLat / norm, sdLng / norm];
      }
    }
  }
  return { pos: bestPos, color: bestColor, dir: bestDir, trackIdx: bestTrackIdx, segIdx: bestSegIdx };
}

/**
 * Förskjut ett spår lateralt (normalt mot spårriktningen) med offsetM meter.
 * Positiv = höger sett i spårets riktning. Används för att separera parallella linjer.
 */
/**
 * Förskjut ett spår lateralt offsetM meter (positiv = höger sett i spårets riktning).
 *
 * Tangenten beräknas med ett glidande medelvärde (windowSize punkter) för att
 * undvika "darriga" parallella linjer när GTFS-datan har mikro-hack.
 * Normalen roteras 90° medurs i skärmrymden (Mercator-korrigerat).
 */
function applyLateralOffset(
  coords: [number, number][],
  offsetM: number,
  windowSize = 11,
): [number, number][] {
  if (Math.abs(offsetM) < 0.1 || coords.length < 2) return coords;
  const half = Math.floor(windowSize / 2);
  return coords.map((pt, i) => {
    const cosLat = Math.cos(pt[0] * Math.PI / 180);
    // Glidande medelvärde: tangent från [lo, hi] istället för enstaka grannpar
    const lo = Math.max(0, i - half);
    const hi = Math.min(coords.length - 1, i + half);
    const dlat = coords[hi][0] - coords[lo][0];
    const dlng = coords[hi][1] - coords[lo][1];
    const lenM = Math.hypot(dlat * 111_000, dlng * 111_000 * cosLat) || 1;
    const dLatDeg = -dlng * cosLat * offsetM / lenM;
    const dLngDeg =  dlat * offsetM / (lenM * cosLat);
    return [pt[0] + dLatDeg, pt[1] + dLngDeg] as [number, number];
  });
}

/** Approximate distance (m) from a point to any coord on the track (sampled). */
function approxDistToTrack(
  lat: number, lng: number,
  coords: [number, number][],
  cosLat: number,
): number {
  let best = Infinity;
  const step = Math.max(1, Math.floor(coords.length / 120));
  for (let i = 0; i < coords.length; i += step) {
    const d = Math.hypot((coords[i][0] - lat) * 111_000, (coords[i][1] - lng) * 111_000 * cosLat);
    if (d < best) best = d;
  }
  return best;
}

/** Build cumulative distance array (meters) for every point along a track. */
function buildCumDist(coords: [number, number][], cosLat: number): Float64Array {
  const d = new Float64Array(coords.length);
  for (let i = 1; i < coords.length; i++) {
    const dlat = (coords[i][0] - coords[i - 1][0]) * 111_000;
    const dlng = (coords[i][1] - coords[i - 1][1]) * 111_000 * cosLat;
    d[i] = d[i - 1] + Math.hypot(dlat, dlng);
  }
  return d;
}

/** Linearly interpolate exact [lat, lng] at distance d along the track. */
function interpAtDist(
  coords: [number, number][],
  cumDist: Float64Array,
  d: number,
): [number, number] {
  if (d <= 0) return coords[0];
  const last = cumDist.length - 1;
  if (d >= cumDist[last]) return coords[last];
  let lo = 0, hi = last;
  while (lo < hi - 1) { const mid = (lo + hi) >> 1; if (cumDist[mid] <= d) lo = mid; else hi = mid; }
  const t = (cumDist[lo + 1] - cumDist[lo]) > 0 ? (d - cumDist[lo]) / (cumDist[lo + 1] - cumDist[lo]) : 0;
  return [
    coords[lo][0] + t * (coords[lo + 1][0] - coords[lo][0]),
    coords[lo][1] + t * (coords[lo + 1][1] - coords[lo][1]),
  ];
}

/**
 * Distance-Based Reconstruction — bygger ett NYTT spår utan att modifiera det gamla.
 *
 * 1. Beräknar kumulativt avstånd (meter) för varje punkt.
 * 2. Hittar stationens avstånd D längs spåret (aldrig index-baserat).
 * 3. Definierar perrong-zonen [D-halfM, D+halfM].
 * 4. Bygger ny array: punkter < D-halfM | exakt pa vid D-halfM | exakt pb vid D+halfM | punkter > D+halfM.
 * Ingen punkt existerar inuti zonen → spåret kan aldrig backa eller loopa.
 */
function platformizeTrack(
  rawCoords: [number, number][],
  stations: { pos: [number, number]; dir: [number, number] }[],
  halfM: number,
): [number, number][] {
  if (stations.length === 0 || rawCoords.length < 4) return rawCoords;

  const midLat = rawCoords[Math.floor(rawCoords.length / 2)][0];
  const cosLat = Math.cos((midLat * Math.PI) / 180);
  const cumDist = buildCumDist(rawCoords, cosLat);
  const totalLen = cumDist[cumDist.length - 1];

  type Interval = { dStart: number; dEnd: number; pa: [number, number]; pb: [number, number] };
  const intervals: Interval[] = [];

  for (const s of stations) {
    // Hitta närmaste punkt i dessa koordinater (grov → fin)
    const step = Math.max(1, Math.floor(rawCoords.length / 200));
    let bestD2 = Infinity, bestIdx = 0;
    for (let i = 0; i < rawCoords.length; i += step) {
      const dlat = rawCoords[i][0] - s.pos[0], dlng = (rawCoords[i][1] - s.pos[1]) * cosLat;
      const d2 = dlat * dlat + dlng * dlng;
      if (d2 < bestD2) { bestD2 = d2; bestIdx = i; }
    }
    const rlo = Math.max(0, bestIdx - step), rhi = Math.min(rawCoords.length - 1, bestIdx + step);
    for (let i = rlo; i <= rhi; i++) {
      const dlat = rawCoords[i][0] - s.pos[0], dlng = (rawCoords[i][1] - s.pos[1]) * cosLat;
      const d2 = dlat * dlat + dlng * dlng;
      if (d2 < bestD2) { bestD2 = d2; bestIdx = i; }
    }

    const stDist = cumDist[bestIdx];
    const dStart = Math.max(0, stDist - halfM);
    const dEnd   = Math.min(totalLen, stDist + halfM);

    // Interpolera exakta positioner på spåret (inte offset från neighbor-riktning)
    intervals.push({
      dStart, dEnd,
      pa: interpAtDist(rawCoords, cumDist, dStart),
      pb: interpAtDist(rawCoords, cumDist, dEnd),
    });
  }

  intervals.sort((a, b) => a.dStart - b.dStart);

  // Enpasbygge — rör oss framåt längs spåret, hoppar aldrig bakåt
  const result: [number, number][] = [];
  let m = 0, injected = false;

  for (let i = 0; i < rawCoords.length; i++) {
    const d = cumDist[i];

    // Avancera förbi fullständigt passerade intervall
    while (m < intervals.length && d > intervals[m].dEnd) { m++; injected = false; }

    if (m >= intervals.length || d < intervals[m].dStart) {
      result.push(rawCoords[i]); // utanför alla zoner — behåll
    } else {
      if (!injected) {
        result.push(intervals[m].pa); // exakt D-halfM
        result.push(intervals[m].pb); // exakt D+halfM
        injected = true;
      }
      // Inuti dead zone — hoppa över originalkoordinaten
    }
  }

  return result;
}

/** Offset a map position by dist_m along a normalized direction vector. */
function offsetAlongDir(
  center: [number, number],
  dir: [number, number],
  dist_m: number,
): [number, number] {
  const cosLat = Math.cos((center[0] * Math.PI) / 180);
  return [
    center[0] + (dir[0] * dist_m) / 111_000,
    center[1] + (dir[1] * dist_m) / (111_000 * cosLat),
  ];
}
