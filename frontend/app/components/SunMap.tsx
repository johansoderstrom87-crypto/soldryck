/**
 * Chaikin corner-cutting — 3 iterations ger mjuka bezier-liknande kurvor.
 * Bevarar exakta start/slut-koordinater så angränsande ways fortfarande
 * möts utan glapp.
 */
function chaikin(pts: [number, number][], iterations = 3): [number, number][] {
  if (pts.length < 3) return pts;
  let cur = pts;
  for (let iter = 0; iter < iterations; iter++) {
    const out: [number, number][] = [cur[0]];
    for (let i = 0; i < cur.length - 1; i++) {
      const [lat1, lng1] = cur[i];
      const [lat2, lng2] = cur[i + 1];
      out.push([lat1 + 0.25 * (lat2 - lat1), lng1 + 0.25 * (lng2 - lng1)]);
      out.push([lat1 + 0.75 * (lat2 - lat1), lng1 + 0.75 * (lng2 - lng1)]);
    }
    out.push(cur[cur.length - 1]);
    cur = out;
  }
  return cur;
}

/** Closest point on segment [p1,p2] to (lat,lng). */
function nearestOnSegment(
  lat: number, lng: number,
  [lat1, lng1]: [number, number],
  [lat2, lng2]: [number, number],
): [number, number] {
  const dx = lat2 - lat1, dy = lng2 - lng1;
  const lenSq = dx * dx + dy * dy;
  if (lenSq === 0) return [lat1, lng1];
  const t = Math.max(0, Math.min(1, ((lat - lat1) * dx + (lng - lng1) * dy) / lenSq));
  return [lat1 + t * dx, lng1 + t * dy];
}

